#!/usr/bin/env python3
"""Generate typed built-in themes; JSON remains the reviewed source of truth."""
import argparse,json,re
from pathlib import Path
root=Path(__file__).resolve().parents[1];component=root/'crates/component/src';theme=component/'theme'
args=argparse.ArgumentParser();args.add_argument('--check',action='store_true');check=args.parse_args().check
header='// Generated by script/generate-builtin-theme.py; do not edit by hand.\n'
def write(path,body):
 text=header+body+'\n'
 if check:
  if not path.exists() or path.read_text()!=text:raise SystemExit(f'Stale generated theme: {path.relative_to(root)}')
 else:path.write_text(text)
def quote(s):return json.dumps(s,ensure_ascii=False)
def fields(source,name):
 body=source.split('pub struct '+name+' {',1)[1].split('\n}',1)[0];out={};renamed=None
 for line in body.splitlines():
  rename=re.search(r'#\[serde\(rename = "([^"]+)"\)\]',line)
  if rename:renamed=rename[1]
  m=re.match(r'\s*(?:pub(?:\([^)]*\))?\s+)?(\w+):\s*(.*),$',line)
  if m:out[renamed or m[1]]=(m[1],m[2]);renamed=None
 return out
schema=(theme/'schema.rs').read_text();data=json.loads((theme/'default-theme.json').read_text())['themes']
def color(s):
 assert re.fullmatch(r'#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?',s),s
 return f'gpui::rgba(0x{s[1:]+("ff" if len(s)==7 else "")}).into()'
weights={100:'Thin',200:'ExtraLight',300:'Light',400:'Normal',500:'Medium',600:'Semibold',700:'Bold',800:'ExtraBold',900:'Black'}
for backend in ['registry','wasm_stub']:
 source=(component/f'highlighter/{backend}.rs').read_text();highlight=[]
 for t in data:
  h=t['highlight'];entries=[]
  for key,(field,ty) in fields(source,'HighlightThemeStyle').items():
   if key in h and ty.startswith('Option<'):entries.append(f'{field}: Some({color(h[key])})')
  status=[]
  for key,(field,ty) in fields(source,'StatusColors').items():
   if key in h:status.append(f'{field}: Some({color(h[key])})')
  syntax=[]
  for key,(field,ty) in fields(source,'SyntaxColors').items():
   if key not in h['syntax']:continue
   v=h['syntax'][key];values=[]
   for prop,typ in [('color','color'),('font_style','style'),('font_weight','weight')]:
    val=v.get(prop);value='None'
    if val is not None:
     value='Some('+ (color(val) if typ=='color' else 'FontStyle::'+val.title() if typ=='style' else 'FontWeightContent::'+weights[val])+')'
    values.append(prop+': '+value)
   syntax.append(f'{field}: Some(ThemeStyle {{ '+', '.join(values)+' })')
  entries+=['status: StatusColors { '+', '.join(status)+', ..Default::default() }' if status else 'status: StatusColors::default()', 'syntax: SyntaxColors { '+', '.join(syntax)+', ..Default::default() }']
  highlight.append('HighlightThemeStyle { '+', '.join(entries)+', ..Default::default() }')
 write(component/f'highlighter/builtin_{backend}.rs','pub(crate) fn builtin_highlight(index: usize) -> HighlightThemeStyle { match index {\n'+''.join(f'{i} => {h},\n' for i,h in enumerate(highlight))+'_ => unreachable!("built-in theme index"),\n} }')
configs=[]
for index,t in enumerate(data):
 entries=[]
 for key,(field,ty) in fields(schema,'ThemeConfig').items():
  if key not in t:continue
  v=t[key]
  if key=='colors':
   mapping=fields(schema,'ThemeConfigColors');values=[]
   for k,val in v.items():
    if k in {'description_list_label.background','description_list_label.foreground','drag_border','link.active.foreground','link.foreground','link.hover.foreground','progress_bar.background','slider.bar.background'}:continue # Legacy JSON key is ignored by serde; preserve existing semantics.
    if k not in mapping:raise ValueError('Unknown theme color '+k)
    values.append(mapping[k][0]+': Some('+quote(val)+'.into())')
   value='super::schema::ThemeConfigColors { '+', '.join(values)+', ..Default::default() }'
  elif key=='highlight':value=f'Some(crate::highlighter::builtin_highlight({index}))'
  elif key=='mode':value='ThemeMode::'+v.title()
  elif isinstance(v,bool):value=str(v).lower()
  elif isinstance(v,str):value=quote(v)+'.into()'
  elif isinstance(v,(int,float)):value=str(v)+('.0' if 'f32' in ty and isinstance(v,int) else '')
  else:raise ValueError(key)
  if ty.startswith('Option<') and key!='highlight':value='Some('+value+')'
  entries.append(field+': '+value)
 configs.append('ThemeConfig { '+', '.join(entries)+', ..Default::default() }')
write(theme/'builtin_themes.rs','pub(super) fn builtin_themes() -> Vec<ThemeConfig> { vec![\n'+',\n'.join(configs)+'\n] }')
palette=json.loads((theme/'default-colors.json').read_text());values=[]
def shade(v):
 h,s,l=[float(x.rstrip('%')) for x in v['hslChannel'].split()]
 return f'ShadcnColor {{ scale: {v.get("scale",0)}, hsla: hsl({h}, {s}, {l}) }}'
for key in fields((theme/'color.rs').read_text().replace('pub(crate) struct ShadcnColors','pub struct ShadcnColors'),'ShadcnColors'):
 v=palette[key];value=shade(v) if isinstance(v,dict) else 'HashMap::from(['+', '.join('('+str(c['scale'])+', '+shade(c)+')' for c in v)+'])'
 values.append(key+': '+value)
write(theme/'builtin_palette.rs','fn builtin_palette() -> ShadcnColors { ShadcnColors {\n'+',\n'.join(values)+'\n} }')
